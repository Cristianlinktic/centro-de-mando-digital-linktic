-- ============================================================================
-- 2. FUNCIONES Y TRIGGERS DE SEGURIDAD (SECURITY DEFINER)
-- ============================================================================

CREATE OR REPLACE FUNCTION centro_mando.is_admin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM centro_mando.profiles
        WHERE id = auth.uid() AND user_role IN ('admin', 'superadmin')
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION centro_mando.is_superadmin()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM centro_mando.profiles
        WHERE id = auth.uid() AND user_role = 'superadmin'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION centro_mando.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO centro_mando.profiles (id, user_role, full_name)
    VALUES (
        new.id,
        'viewer', -- Rol por defecto
        COALESCE(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'username')
    )
    ON CONFLICT (id) DO UPDATE
        SET full_name = COALESCE(EXCLUDED.full_name, centro_mando.profiles.full_name);
    RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created_centro_mando ON auth.users;
CREATE TRIGGER on_auth_user_created_centro_mando
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE PROCEDURE centro_mando.handle_new_user();

