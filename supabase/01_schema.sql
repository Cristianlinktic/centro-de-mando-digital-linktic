CREATE TABLE IF NOT EXISTS centro_mando.profiles (
    id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL PRIMARY KEY,
    user_role TEXT DEFAULT 'viewer',
    full_name TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE centro_mando.profiles DROP CONSTRAINT IF EXISTS profiles_user_role_check;
ALTER TABLE centro_mando.profiles ADD CONSTRAINT profiles_user_role_check
    CHECK (user_role IN ('superadmin', 'admin', 'viewer'));

